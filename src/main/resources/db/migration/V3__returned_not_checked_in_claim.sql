-- 通用 SQL 子集，可同时在 PostgreSQL 与 H2(PostgreSQL 模式) 上由 Flyway 执行

-- 申诉工单补充：读者申报的还书机与还书时刻、终判责任方、信用是否已随结案修复
ALTER TABLE claims ADD COLUMN kiosk_code          VARCHAR(32);
ALTER TABLE claims ADD COLUMN claimed_returned_at TIMESTAMP;
ALTER TABLE claims ADD COLUMN held_at             TIMESTAMP;
ALTER TABLE claims ADD COLUMN outcome             VARCHAR(24);
ALTER TABLE claims ADD COLUMN credit_repaired     BOOLEAN;

-- 罚款单补充：申诉核查期间暂缓增长的标记（不减免，仅冻结日累计）
ALTER TABLE fines ADD COLUMN growth_hold BOOLEAN NOT NULL DEFAULT FALSE;

-- 自助还书机日志（含扫描失败/书箱卡滞等异常），供馆员核查
CREATE TABLE kiosk_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_code    VARCHAR(32) NOT NULL,
    kiosk_code      VARCHAR(32) NOT NULL,
    -- SCAN_FAIL 扫描失败 / BIN_JAM 书箱卡滞 / OK 正常回收
    event_type      VARCHAR(16) NOT NULL,
    item_barcode    VARCHAR(32),
    reader_card_no  VARCHAR(32),
    occurred_at     TIMESTAMP NOT NULL,
    detail          VARCHAR(512)
);
CREATE INDEX idx_kiosk_time ON kiosk_logs(library_code, occurred_at);
CREATE INDEX idx_kiosk_barcode ON kiosk_logs(item_barcode);

-- 申诉证据链（读者举证 + 馆员核查：机日志/监控编号/书箱清点/入库记录）
CREATE TABLE claim_evidences (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id     BIGINT NOT NULL REFERENCES claims(id),
    -- KIOSK_LOG 还书机日志 / CAMERA 监控编号 / BIN_COUNT 书箱清点 /
    -- CHECKIN_RECORD 馆员入库记录 / READER 读者补充证据 / REOPEN 重新核查说明
    kind         VARCHAR(20) NOT NULL,
    -- READER 读者提交 / STAFF 馆员核查登记
    source       VARCHAR(16) NOT NULL,
    content      VARCHAR(1024) NOT NULL,
    ref_no       VARCHAR(64),
    staff        VARCHAR(64),
    created_at   TIMESTAMP NOT NULL,
    created_by   VARCHAR(64)
);
CREATE INDEX idx_claim_evidences_claim ON claim_evidences(claim_id, created_at);

-- 借阅信用记录：逾期/丢书产生扣减，馆方确认漏入库等责任时随申诉结案修复
CREATE TABLE credit_records (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id    BIGINT NOT NULL REFERENCES readers(id),
    loan_id      BIGINT REFERENCES loans(id),
    claim_id     BIGINT REFERENCES claims(id),
    -- OVERDUE 逾期扣减 / LOST 丢书扣减 / REPAIR 信用修复
    type         VARCHAR(16) NOT NULL,
    change       INTEGER NOT NULL,
    reason       VARCHAR(512) NOT NULL,
    created_at   TIMESTAMP NOT NULL
);
CREATE INDEX idx_credit_reader ON credit_records(reader_id, created_at);

