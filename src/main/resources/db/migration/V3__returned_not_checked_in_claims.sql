-- “已还未入库”申诉增强：证据链、核查留痕、罚款冻结、借阅信用
-- 通用 SQL 子集，可同时在 PostgreSQL 与 H2(PostgreSQL 模式) 上由 Flyway 执行

-- 自助还书机日志：投入/扫描成功或失败均记录，供申诉核查
CREATE TABLE self_checkin_logs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code     VARCHAR(32) NOT NULL,
    library_id       BIGINT NOT NULL REFERENCES libraries(id),
    item_barcode     VARCHAR(32),
    -- SCAN_SUCCESS 扫描成功并入库 / SCAN_FAILED 扫描失败（读者已投书，书落书箱）
    result           VARCHAR(16) NOT NULL,
    occurred_at      TIMESTAMP NOT NULL,
    bin_no           VARCHAR(32),
    camera_ref       VARCHAR(64),
    note             VARCHAR(512),
    created_at       TIMESTAMP NOT NULL
);
CREATE INDEX idx_checkin_barcode_time ON self_checkin_logs(item_barcode, occurred_at);
CREATE INDEX idx_checkin_library_time ON self_checkin_logs(library_id, occurred_at);

-- 读者信用流水：逾期/丢书计负，馆方漏入库定责时同案修复
CREATE TABLE credit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id   BIGINT NOT NULL REFERENCES readers(id),
    loan_id     BIGINT REFERENCES loans(id),
    claim_id    BIGINT,
    -- OVERDUE 逾期 / LOST 丢书 / REPAIR 馆方责任修复
    type        VARCHAR(16) NOT NULL,
    points      INTEGER NOT NULL,
    reason      VARCHAR(512) NOT NULL,
    staff       VARCHAR(64),
    created_at  TIMESTAMP NOT NULL
);
CREATE INDEX idx_credit_reader ON credit_events(reader_id, created_at);

